"""stable category keys and import source hash

Gives every category a stable, machine-readable identity (`categories.key`) that is
independent of its display name, and records the SHA-256 of an uploaded file
(`import_batches.source_hash`) so an identical re-upload is recognisable.

Why `key` matters: stored analysis results point at a category row, and a caller's
taxonomy points at it by key. Renaming "Delivery Issues" to "Shipping & Delivery" then
changes a label and nothing else. Before this, the name *was* the identity, so a rename
would have orphaned every earlier result (recorded as limitation 3 of Milestone 5A).

**This is not the autogenerated version.** Alembic proposed adding `key` as NOT NULL with
no default, which fails on any database that already holds the 24 seeded categories - the
development database and every environment that ran Milestone 5A. It is done in the usual
three steps instead:

    1. add the column nullable
    2. backfill it
    3. make it NOT NULL, then add the unique indexes

The backfill carries the 24 key/name pairs explicitly rather than importing the packaged
taxonomy. A migration must keep doing the same thing years later, whatever the application
code has become; importing today's loader into it would make history depend on the present.
Rows the list does not cover (an organisation's own categories) get a key derived from
their name by the same rule that generated these pairs.

Revision ID: 0002
Revises: 0001
Created: 2026-09-13 13:32:53.121604+00:00

"""
