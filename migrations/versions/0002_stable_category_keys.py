# The same rule that produced those keys, in SQL: "&" and "/" become " and ", anything else
# that is not a letter or digit becomes "_", then runs of "_" collapse and the ends are
# trimmed. Used for any category the list above does not name.
DERIVE_KEY_SQL = """
    UPDATE categories
       SET key = trim(both '_' from regexp_replace(
                   regexp_replace(lower(name), '[&/]', ' and ', 'g'),
                   '[^a-z0-9]+', '_', 'g'))
     WHERE key IS NULL
"""


