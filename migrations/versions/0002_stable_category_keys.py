    connection = op.get_bind()

    for key, name in SEEDED_KEYS:
        connection.execute(
            sa.text(
                "UPDATE categories SET key = :key "
                " WHERE organisation_id IS NULL AND name = :name AND key IS NULL"
            ),
            {"key": key, "name": name},
        )

